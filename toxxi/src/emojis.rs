pub static ALL_EMOJIS: LazyLock<HashSet<&'static str>> =
    LazyLock::new(|| EMOJIS.iter().map(|&(_, e)| e).collect());

pub static PRIORITY_MAP: LazyLock<HashMap<&'static str, usize>> = LazyLock::new(|| {
    let mut m = HashMap::new();
    let mut current_priority = 0;
    for &(_, emoji) in EMOJIS {
        if !m.contains_key(emoji) {
            m.insert(emoji, current_priority);
            current_priority += 1;
        }
    }
    m
});

pub fn is_emoji(s: &str) -> bool {
    ALL_EMOJIS.contains(s)
}

pub fn get_emoji_priority(emoji: &str) -> Option<usize> {
    PRIORITY_MAP.get(emoji).copied()
}
